export const SCIENCE_QUESTIONS: ScienceQuestion[] = entries.map(([id, topic, prompt, answer, wrong1, wrong2, explanation]) => ({
  id, topic, prompt, answer, choices: [answer, wrong1, wrong2], explanation,
}));

export function scienceDeck(seed: number): ScienceQuestion[] {
  const rng = random(seed);
  const topics = [...new Set(SCIENCE_QUESTIONS.map(q => q.topic))];
  const pools = topics.map(topic => shuffle(SCIENCE_QUESTIONS.filter(q => q.topic === topic), rng));
  return Array.from({ length: 6 }, (_, i) => shuffle(pools.map(pool => pool[i]), rng)).flat()
    .slice(0, 9).map(q => ({ ...q, choices: shuffle(q.choices, rng) }));
}
