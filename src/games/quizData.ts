export type QuizMode = QuizTopic | 'mixed';
export type QuizQuestion = Question & {
  id: string;
  topic: QuizTopic;
  flag?: string;
  flagDescription?: string;
};
export const quizModeLabel = (mode: QuizMode) => mode === 'mixed' ? '모두 섞기' : QUIZ_TOPICS[mode].label;
export const isQuizMode = (value: unknown): value is QuizMode =>
  typeof value === 'string' && (value === 'mixed' || Object.hasOwn(QUIZ_TOPICS, value));

// Each tuple contains the correct answer followed by three distractors. The deck
// shuffles choices before display; authored facts and explanations stay together.
type Entry = [id: string, prompt: string, answer: string, distractors: [string, string, string], explanation: string];
const questions = (topic: QuizTopic, entries: Entry[]): QuizQuestion[] => entries.map(
  ([id, prompt, answer, distractors, explanation]) => ({ id, topic, prompt, answer, choices: [answer, ...distractors], explanation, level: 1 }),
);

