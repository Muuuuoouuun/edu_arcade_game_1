// Aspect-preserving delivery encodes; source illustrations remain unchanged.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('..', import.meta.url));
const sourceDir = path.join(root, 'art-source/defense/gates');
const outputDir = path.join(root, 'public/defense/gates');
mkdirSync(outputDir, { recursive: true });
const sources = JSON.parse(readFileSync(path.join(sourceDir, 'sources.json'), 'utf8'));
const assets = {}, files = [];
for (const [id, { size: [w, h], bounds: [left, top, right, bottom] }] of Object.entries(sources.images)) {
  const source = path.join(sourceDir, `${id}.png`), destination = path.join(outputDir, `${id}.webp`);
  execFileSync('ffmpeg', ['-hide_banner', '-loglevel', 'error', '-y', '-i', source,
    '-vf', 'scale=512:-1', '-c:v', 'libwebp', '-quality', '88', '-compression_level', '6', destination]);
  // Normalize the visible silhouette, keeping all transparent source margins.
  const scale = Math.min(128 / (right - left), 145 / (bottom - top));
  const round = n => Math.round(n * 1000) / 1000;
  assets[id] = { src: `/defense/gates/${id}.webp`, x: round(-(left + right) / 2 * scale),
    y: round(-bottom * scale), width: round(w * scale), height: round(h * scale) };
  const data = readFileSync(destination);
  files.push({ id, file: `${id}.webp`, bytes: data.length, sha256: createHash('sha256').update(data).digest('hex'),
    sourceSha256: createHash('sha256').update(readFileSync(source)).digest('hex') });
}
writeFileSync(path.join(root, 'src/games/defense/gateArt.ts'),
  '// Generated by tools/build-defense-gates.mjs. Full source images are preserved.\n' +
  'export const GATE_ART = ' + JSON.stringify(assets, null, 2) + ' as const;\n');
writeFileSync(path.join(outputDir, 'manifest.json'), JSON.stringify({ encoding: '512px WebP, original aspect and alpha', files }, null, 2) + '\n');
console.log(`Built ${files.length} gates (${files.reduce((total, f) => total + f.bytes, 0)} bytes).`);
