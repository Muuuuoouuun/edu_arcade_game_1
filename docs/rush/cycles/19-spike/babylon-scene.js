// Minimal toon scene in Babylon.js: ground + 40 thin-instanced enemies (sphere+box merged), cel shading, outline.
import { Engine } from '@babylonjs/core/Engines/engine';
import { Scene } from '@babylonjs/core/scene';
import { FreeCamera } from '@babylonjs/core/Cameras/freeCamera';
import { HemisphericLight } from '@babylonjs/core/Lights/hemisphericLight';
import { DirectionalLight } from '@babylonjs/core/Lights/directionalLight';
import { MeshBuilder } from '@babylonjs/core/Meshes/meshBuilder';
import { Mesh } from '@babylonjs/core/Meshes/mesh';
import { Vector3, Matrix } from '@babylonjs/core/Maths/math.vector';
import { Color3, Color4 } from '@babylonjs/core/Maths/math.color';
import { StandardMaterial } from '@babylonjs/core/Materials/standardMaterial';
import { CellMaterial } from '@babylonjs/materials/cell/cellMaterial';
import { SceneInstrumentation } from '@babylonjs/core/Instrumentation/sceneInstrumentation';
import '@babylonjs/core/Rendering/outlineRenderer';
import '@babylonjs/core/Meshes/thinInstanceMesh';

const canvas = document.getElementById('c');
const engine = new Engine(canvas, true);
const scene = new Scene(engine);
scene.clearColor = new Color4(0.25, 0.7, 0.85, 1);
const cam = new FreeCamera('cam', new Vector3(0, 16, 14), scene);
cam.setTarget(new Vector3(0, 0, -2));
cam.fov = 0.6;
new HemisphericLight('h', new Vector3(0, 1, 0), scene).intensity = 0.6;
const sun = new DirectionalLight('d', new Vector3(0.4, -1, -0.5), scene); sun.intensity = 1.1;
const ground = MeshBuilder.CreateGround('g', { width: 30, height: 30 }, scene);
const gm = new StandardMaterial('gm', scene); gm.diffuseColor = new Color3(0.53, 0.83, 0.35); gm.specularColor = new Color3(0, 0, 0); ground.material = gm;
const body = MeshBuilder.CreateSphere('b', { diameter: 1, segments: 12 }, scene); body.position.y = 0.5;
const club = MeshBuilder.CreateBox('k', { width: 0.2, height: 1, depth: 0.2 }, scene); club.position.set(0.4, 0.9, 0.3);
const enemy = Mesh.MergeMeshes([body, club], true, true);
const cell = new CellMaterial('cell', scene); cell.diffuseColor = new Color3(0.89, 0.27, 0.25); cell.computeHighLevel = true;
enemy.material = cell;
enemy.renderOutline = true; enemy.outlineColor = new Color3(0.11, 0.08, 0.2); enemy.outlineWidth = 0.05;
const mats = [];
for (let i = 0; i < 40; i++) mats.push(Matrix.Translation(-9 + (i % 8) * 2.6, 0, -8 + Math.floor(i / 8) * 2.6));
enemy.thinInstanceAdd(mats);
const inst = new SceneInstrumentation(scene);
let frames = 0;
engine.runRenderLoop(() => { scene.render(); if (++frames === 30) window.__stats = { calls: inst.drawCallsCounter.current, active: scene.getActiveMeshes().length }; });
